package config

import (
	"database/sql"
	"fmt"
	"log"
	_ "github.com/lib/pq"
)

var DB *sql.DB

var connStr = "user=postgres password=root dbname=webapp sslmode=disable host=localhost port=5432"
func ConnectDB() *sql.DB {
	var err error
	DB, err := sql.Open("postgres", connStr)
	if err != nil {
		log.Fatal(err)
	}
	return DB
}
// InitDB initialise la connexion à la base de données PostgreSQL
func InitDB() {
	// Modifiez cette chaîne de connexion selon votre environnement
	var err error
	DB, err = sql.Open("postgres", connStr)
	if err != nil {
		log.Fatal(err)
	}

	if err = DB.Ping(); err != nil {
		log.Fatal(err)
	}

	query := `-- SQL Schema for PostgreSQL
-- Generated by TurboStack

CREATE TABLE IF NOT EXISTS usertable (
	id INTEGER PRIMARY KEY UNIQUE,
	username VARCHAR(255) UNIQUE
);

`
	_, err = DB.Exec(query)
	if err != nil {
		fmt.Errorf("échec lors de l'initialisation des tables: %w", err)
	}
	fmt.Println("Successfully connected to database")
}
